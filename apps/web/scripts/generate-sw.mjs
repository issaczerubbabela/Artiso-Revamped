// Post-build step: writes out/sw.js, a service worker that precaches the whole
// static export so the app cold-starts with no network (invariant 5, "sync is
// additive": the app must be fully usable offline -- not just once loaded).
//
// The cache name is a hash of every precached file, so each deploy gets a fresh
// cache and the previous one is deleted when the new worker activates. The new
// worker deliberately does NOT skipWaiting: an open session keeps the version
// whose lazily loaded chunks it was built against, and the update takes over on
// the next launch.
//
// Only "/" is precached as HTML. Static hosts (Cloudflare Pages, Vercel)
// redirect /index.html -> /, and Safari refuses to serve a redirected response
// from a service worker for a navigation.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'out');

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => (entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)])),
  );
  return files.flat();
}

// Which exported files the app needs offline. HTML other than the entry point,
// RSC payloads (*.txt, only used by <Link> navigation, which this single-page
// app never does), source maps and host config files are skipped.
function isPrecached(url) {
  if (url === '/sw.js' || url === '/_headers' || url === '/_redirects') return false;
  if (url.endsWith('.html') || url.endsWith('.txt') || url.endsWith('.map')) return false;
  return true;
}

const files = (await walk(outDir)).sort();
const hash = createHash('sha256');
const urls = ['/'];
hash.update(await readFile(join(outDir, 'index.html')));
for (const file of files) {
  const url = '/' + relative(outDir, file).split(sep).join('/');
  if (!isPrecached(url)) continue;
  urls.push(url);
  hash.update(url);
  hash.update(await readFile(file));
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/generate-sw.mjs at build time -- do not edit.
const CACHE = 'artiso-${version}';
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('artiso-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  // Supabase (auth, REST, storage) and anything else cross-origin go straight
  // to the network; sync has its own offline queue.
  if (url.origin !== self.location.origin) return;

  // Single-page app: every navigation is the cached entry point.
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('/', { cacheName: CACHE }).then((hit) => hit || fetch(request)));
    return;
  }

  event.respondWith(
    caches.match(request, { cacheName: CACHE, ignoreSearch: true }).then(
      (hit) =>
        hit ||
        fetch(request).catch(() => new Response('', { status: 504, statusText: 'Offline' })),
    ),
  );
});
`;

await writeFile(join(outDir, 'sw.js'), sw);
console.log(`sw.js: ${urls.length} files precached as artiso-${version}`);
